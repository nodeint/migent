import { ENV_CATALOG } from '../env.js';
import { EXIT_CATALOG, EXIT_FAMILIES, EXIT_FAMILY_TITLES } from '../exits.js';
import { CLI_CONTRACTS, KNOWN_SHAPES, SESSION_EVENTS, SESSION_FILES } from '../index-registry.js';
import { SESSION_STATUS_CATALOG } from '../session-status.js';
import { collectIdentities, schemaPath } from './schemas.js';

type Node = { [key: string]: unknown };
const isNode = (value: unknown): value is Node => typeof value === 'object' && value !== null && !Array.isArray(value);

const BANNER = '<!-- Generated by `pnpm generate` from @nodeint/migent-contracts. Do not edit. -->\n';

/** Which reference file renders an identity. */
function fileFor(identity: string): string {
  const path = schemaPath(identity);
  if (path.startsWith('config/')) return 'config.md';
  if (path.startsWith('workflow/')) return 'workflow.md';
  if (path.startsWith('exit/')) return 'exit-codes.md';
  if (path.startsWith('env/')) return 'env.md';
  if (path === 'session/session-status-entry.json') return 'session-statuses.md';
  if (path.startsWith('session/')) return 'session-files.md';
  return 'cli-output.md';
}

const anchor = (identity: string) => schemaPath(identity).replace(/[^a-z0-9]+/gi, '-');
const link = (identity: string, from: string, title: string) => {
  const file = fileFor(identity);
  return `[${title}](${file === from ? '' : file}#${anchor(identity)})`;
};
const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const code = (text: string) => `\`${cell(text)}\``;

interface Row {
  path: string;
  type: string;
  required: boolean;
  notes: string;
  description: string;
}

/** Parenthesize a composite type so a following `[]` or `map of` binds to all of it. */
const group = (text: string) => (/ \\\| |^map of /.test(text) ? `(${text})` : text);

function label(schema: unknown, from: string, root: Node | null): string {
  if (!isNode(schema)) return 'any';
  if (typeof schema.$id === 'string' && schema !== root) return link(schema.$id, from, String(schema.title ?? schemaPath(schema.$id)));
  if (Array.isArray(schema.anyOf)) return schema.anyOf.map((item) => label(item, from, root)).join(' \\| ');
  if (schema.const !== undefined) return code(JSON.stringify(schema.const));
  if (Array.isArray(schema.enum)) return schema.enum.map((item) => code(JSON.stringify(item))).join(' \\| ');
  if (schema.type === 'array') return `${group(label(schema.items, from, root))}[]`;
  if (schema.type === 'object') return objectLabel(schema, from, root);
  return typeof schema.type === 'string' ? schema.type : 'any';
}

/** Values schema of a map-like object: the first pattern property, else `additionalProperties`. */
function mapValues(schema: Node): unknown {
  return isNode(schema.patternProperties) ? Object.values(schema.patternProperties)[0] : schema.additionalProperties;
}

function objectLabel(schema: Node, from: string, root: Node | null): string {
  if (isNode(schema.properties) && Object.keys(schema.properties).length > 0) return 'object';
  const values = mapValues(schema);
  return isNode(values) ? `map of ${group(label(values, from, root))}` : 'object';
}

function notes(schema: Node): string {
  const out: string[] = [];
  for (const key of ['default', 'minimum', 'maximum', 'minItems', 'maxItems', 'pattern', 'format']) {
    if (schema[key] !== undefined) out.push(`${key}: ${code(JSON.stringify(schema[key]))}`);
  }
  return out.join('; ');
}

function describeOf(schema: unknown): string {
  if (!isNode(schema)) return '';
  if (typeof schema.description === 'string') return schema.description;
  if (Array.isArray(schema.anyOf)) return schema.anyOf.map(describeOf).find(Boolean) ?? '';
  return '';
}

interface RowsContext {
  readonly from: string;
  readonly root: Node | null;
  readonly out: Row[];
}

/** Field rows of a schema: inline nested objects expand with a dotted path, identified ones are linked. */
function rows(schema: unknown, prefix: string, context: RowsContext): void {
  if (!isNode(schema)) return;
  if (typeof schema.$id === 'string' && schema !== context.root) return;
  if (Array.isArray(schema.anyOf)) {
    for (const item of schema.anyOf) rows(item, prefix, context);
    return;
  }
  if (schema.type === 'array') {
    rows(schema.items, `${prefix}[]`, context);
    return;
  }
  if (schema.type !== 'object') return;
  propertyRows(schema, prefix, context);
  const values = mapValues(schema);
  if (isNode(values)) rows(values, `${prefix}.*`, context);
}

function propertyRows(schema: Node, prefix: string, context: RowsContext): void {
  if (!isNode(schema.properties)) return;
  const { from, root, out } = context;
  const required = new Set(Array.isArray(schema.required) ? (schema.required as string[]) : []);
  for (const [name, property] of Object.entries(schema.properties)) {
    if (!isNode(property)) continue;
    const path = prefix ? `${prefix}.${name}` : name;
    out.push({
      path,
      type: label(property, from, root),
      required: required.has(name),
      notes: notes(property),
      description: describeOf(property),
    });
    rows(property, path, context);
  }
}

function section(identity: string, node: Node, options: { from: string; extra?: string }): string {
  const { from, extra = '' } = options;
  const title = String(node.title ?? schemaPath(identity));
  const lines = [`<a id="${anchor(identity)}"></a>`, `### ${title}`, '', `Schema: ${code(identity)}`, ''];
  if (typeof node.description === 'string') lines.push(node.description, '');
  if (extra) lines.push(extra, '');
  lines.push(`Type: ${label(node, from, node)}`, '');
  const out: Row[] = [];
  rows(node, '', { from, root: node, out });
  if (out.length > 0) {
    lines.push('| Field | Type | Required | Notes | Description |', '| --- | --- | --- | --- | --- |');
    for (const row of out) lines.push(`| ${code(row.path)} | ${row.type} | ${row.required ? 'yes' : 'no'} | ${cell(row.notes)} | ${cell(row.description)} |`);
    lines.push('');
  }
  return lines.join('\n');
}

function sectionsFor(file: string, header: string[], extras: Map<string, string> = new Map()): string {
  const parts = [BANNER, ...header];
  for (const [identity, node] of collectIdentities()) {
    if (fileFor(identity) === file) parts.push(section(identity, node, { from: file, extra: extras.get(identity) }));
  }
  return `${parts.join('\n')}\n`.replace(/\n{3,}/g, '\n\n');
}

function cliOutput(): string {
  const commands = new Map<string, string[]>();
  for (const entry of CLI_CONTRACTS) {
    const identity = (entry.schema as Node).$id as string;
    const list = commands.get(identity) ?? [];
    list.push(`${entry.commands.map(code).join(', ')} (${entry.class}, ${entry.framing})`);
    commands.set(identity, list);
  }
  const extras = new Map([...commands].map(([identity, list]) => [identity, `Emitted by: ${list.join('; ')}`]));
  for (const shape of KNOWN_SHAPES) {
    const identity = (shape as Node).$id as string;
    extras.set(identity, 'Opt-in description of a persisted file. No command guarantees it: such files are written by any past Migent version, so treat every field as optional.');
  }
  return sectionsFor('cli-output.md', ['# CLI output reference', '', 'Fields of every `--json` / `-o json` payload. Output contracts are open: consumers must ignore unknown fields.', ''], extras);
}

function config(): string {
  return sectionsFor('config.md', ['# Config reference', '', 'Structure of `.migent/config.yaml` and `.migent/config.local.yaml`.', '']);
}

function workflow(): string {
  return sectionsFor('workflow.md', ['# Workflow reference', '', 'Structure of a workflow file at the current `schema_version`. Unknown keys are errors.', '']);
}

function exitCodes(): string {
  const lines = [BANNER, '# Exit codes', '', '| Code | Name | Command family | Meaning |', '| --- | --- | --- | --- |'];
  for (const entry of EXIT_CATALOG) {
    for (const family of EXIT_FAMILIES) {
      const text = (entry.descriptions as Record<string, string | undefined>)[family];
      if (text) lines.push(`| ${entry.code} | ${code(entry.name)} | ${cell(EXIT_FAMILY_TITLES[family])} | ${cell(text)} |`);
    }
  }
  return `${lines.join('\n')}\n`;
}

function env(): string {
  const lines = [BANNER, '# Environment variables', '', '| Name | Kind | Value rule | Processes | Description |', '| --- | --- | --- | --- | --- |'];
  for (const item of ENV_CATALOG) {
    let rule: string;
    if (item.kind === 'flag') rule = `on for ${item.enabling_values.map(code).join(', ')}`;
    else if (item.kind === 'path') rule = `default ${code(item.default)}`;
    else rule = `default ${code(item.default_value)} for ${code(item.child)}`;
    lines.push(`| ${code(item.name)} | ${item.kind} | ${rule} | ${item.processes.join(', ')} | ${cell(item.description)} |`);
  }
  return `${lines.join('\n')}\n`;
}

function sessionStatuses(): string {
  const flags = ['ends_scheduling', 'manually_completable', 'refreshable', 'closed', 'terminal_fields'] as const;
  const head = ['Name', 'Kind', 'Precedence', 'Exit', ...flags, 'Manifest', 'Resolution'];
  const lines = [BANNER, '# Session statuses', '', `| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`];
  for (const item of SESSION_STATUS_CATALOG) {
    const stop: { event: string; from?: string } | null = item.resolution;
    const resolution = [stop?.event, stop?.from && `from ${stop.from}`].filter(Boolean).join(' ');
    const cells = [code(item.name), item.kind, item.precedence === null ? '' : String(item.precedence), item.exit ?? '', ...flags.map((flag) => (item[flag] ? 'yes' : '')), item.manifest ?? '', resolution];
    lines.push(`| ${cells.join(' | ')} |`);
  }
  lines.push('', sectionsFor('session-statuses.md', ['## Row schema', '']).replace(BANNER, '').trim());
  return `${lines.join('\n')}\n`;
}

function sessionFiles(): string {
  const file = 'session-files.md';
  const header = [
    '# Session files reference',
    '',
    'Structure of the files under `.migent/sessions/<id>/` and of every `events.jsonl` record. Objects are open: readers must ignore unknown fields.',
    '',
    'Each entry has a stability class. `guaranteed`: a breaking change needs a major release, and a format change bumps `schema_version` and adds a union member. `known`: an opt-in description, never a guarantee.',
    '',
  ];
  const parts = [BANNER, ...header, '## Files', ''];
  for (const entry of SESSION_FILES) {
    const node = entry.schema as Node;
    parts.push(section(node.$id as string, node, { from: file, extra: `Path: ${code(entry.path)}; class: ${entry.class}; framing: ${entry.framing}` }));
  }
  parts.push('## Events', '', 'One record schema per event name. Client events (`provider.*`, `verify.*` and the correction events) accept a current and a historical form.', '');
  for (const entry of SESSION_EVENTS) {
    const node = entry.schema as Node;
    parts.push(section(node.$id as string, node, { from: file, extra: `Event: ${code(entry.event)}; class: ${entry.class}` }));
  }
  return `${parts.join('\n')}\n`.replace(/\n{3,}/g, '\n\n');
}

/** `{ "docs/reference/<file>.md": content }`. */
export function generateMarkdownFiles(): Record<string, string> {
  return {
    'docs/reference/cli-output.md': cliOutput(),
    'docs/reference/config.md': config(),
    'docs/reference/workflow.md': workflow(),
    'docs/reference/exit-codes.md': exitCodes(),
    'docs/reference/env.md': env(),
    'docs/reference/session-statuses.md': sessionStatuses(),
    'docs/reference/session-files.md': sessionFiles(),
  };
}
